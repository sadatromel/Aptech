CREATE TABLE IF NOT EXISTS `letters_of_credit` (
  `lc_id` INT(11) NOT NULL AUTO_INCREMENT,
  `lc_number` VARCHAR(100) NOT NULL,
  `lc_type` ENUM('master_lc', 'back_to_back_lc', 'contract') DEFAULT 'master_lc',
  `buyer_id` INT(11) DEFAULT NULL,
  `customer_id` INT(11) DEFAULT NULL,
  `opening_bank` VARCHAR(150) DEFAULT NULL,
  `advising_bank` VARCHAR(150) DEFAULT NULL,
  `lc_amount` DECIMAL(15,2) DEFAULT 0.00,
  `utilized_amount` DECIMAL(15,2) DEFAULT 0.00,
  `currency` VARCHAR(10) DEFAULT 'USD',
  `issue_date` DATE DEFAULT NULL,
  `expiry_date` DATE DEFAULT NULL,
  `shipment_date` DATE DEFAULT NULL,
  `tenure_days` INT(11) DEFAULT 60,
  `status` ENUM('active', 'amendment', 'fully_negotiated', 'expired', 'cancelled') DEFAULT 'active',
  `notes` TEXT DEFAULT NULL,
  `created_by` INT(11) DEFAULT NULL,
  `created_at` DATETIME DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`lc_id`),
  KEY `idx_lc_number` (`lc_number`),
  KEY `idx_buyer_id` (`buyer_id`),
  KEY `idx_status` (`status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
